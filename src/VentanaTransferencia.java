    /**
     * Pide el saldo actual al servidor y lo muestra. Se consulta cada vez porque otro cliente pudo haber cambiado el saldo desde que se ingresó.
     */
    private void cargarSaldo() {
        new SwingWorker<Double, Void>() {
            @Override
            protected Double doInBackground() throws Exception {
                return ClienteRed.consultarSaldo(sesion);
            }

            @Override
            protected void done() {
                try {
                    lblSaldo.setText("Saldo actual: " + Formato.formatearMonto(get()));
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                } catch (ExecutionException e) {
                    lblSaldo.setText("Saldo actual: no disponible");
                    Mensajes.mostrarError(VentanaTransferencia.this, e, "Transferencia");
                }
            }
        }.execute();
    }

    /**
     * Se llama cuando el servidor ya revisó la transferencia. Muestra el titular de la cuenta destino y el monto, y pregunta si desea continuar.
     * Si el cliente acepta envía la petición que ejecuta la transferencia, si no se queda en esta pantalla.
     */
    private void confirmarTransferencia(String cuentaDestino, double monto, String titular) {
        int opcion = JOptionPane.showConfirmDialog(this,
                "Titular de la cuenta destino: " + titular + "\nMonto: " + Formato.formatearMonto(monto) + "\n\n¿Desea continuar?",
                "Confirmar transferencia",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);
        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        habilitarControles(false);

        new SwingWorker<ResultadoOperacion, Void>() {
            // Se ejecuta en un hilo aparte: el servidor descuenta de la cuenta de origen, suma a la cuenta destino y registra la transacción
            @Override
            protected ResultadoOperacion doInBackground() throws Exception {
                return ClienteRed.transferir(sesion, cuentaDestino, monto);
            }

            @Override
            protected void done() {
                habilitarControles(true);
                try {
                    ResultadoOperacion resultado = get();
                    // Se muestra el aviso de transacción exitosa y al regresar de él se cierra esta ventana para volver al menú principal
                    new VentanaTransaccionExitosa(VentanaTransferencia.this, true, sesion, resultado,
                            "Transferencia realizada con éxito", null).setVisible(true);
                    dispose();
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                } catch (ExecutionException e) {
                    Mensajes.mostrarError(VentanaTransferencia.this, e, "Transferencia");
                }
            }
        }.execute();
    }

    /**
     * Habilita o deshabilita los campos y botones de la ventana, se usa mientras se espera la respuesta del servidor.
     */
    private void habilitarControles(boolean habilitar) {
        txtCuentaDestino.setEnabled(habilitar);
        txtMonto.setEnabled(habilitar);
        btnTransferir.setEnabled(habilitar);
        btnCancelar.setEnabled(habilitar);
    }

