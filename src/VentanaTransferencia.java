    /**
     * Botón Transferir: valida la cuenta destino y el monto, y le pide al servidor que revise la transferencia sin ejecutarla.
     * Si la cuenta destino no existe o es la misma cuenta de origen se muestra "Cuenta destino no válida", si el monto no es válido "Monto no válido"
     * y si el saldo no alcanza "Saldo insuficiente". En esos casos la transferencia no se realiza ni se registra.
     */
    private void btnTransferirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTransferirActionPerformed
        String cuentaDestino = txtCuentaDestino.getText().trim();
        if (!Formato.esNumero(cuentaDestino)) {
            JOptionPane.showMessageDialog(this, "Cuenta destino no válida", "Transferencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Double montoLeido = Mensajes.leerMonto(this, txtMonto.getText(), "Transferencia");
        if (montoLeido == null) {
            return;
        }
        double monto = montoLeido;

        // Mientras se espera la respuesta del servidor se deshabilitan los controles para evitar peticiones repetidas
        habilitarControles(false);

        new SwingWorker<String, Void>() {
            // Se ejecuta en un hilo aparte: el servidor revisa la transferencia y devuelve el titular de la cuenta destino
            @Override
            protected String doInBackground() throws Exception {
                return ClienteRed.validarTransferencia(sesion, cuentaDestino, monto);
            }

            // Se ejecuta en el hilo de eventos cuando el servidor ya respondió
            @Override
            protected void done() {
                habilitarControles(true);
                try {
                    confirmarTransferencia(cuentaDestino, monto, get());
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                } catch (ExecutionException e) {
                    Mensajes.mostrarError(VentanaTransferencia.this, e, "Transferencia");
                }
            }
        }.execute();
    }//GEN-LAST:event_btnTransferirActionPerformed

