    private final javax.swing.Timer temporizador;

    /**
     * Crea la ventana del servidor e inicia el servidor.
     */
    public VentanaServidor(SistemaCajero sistema) {
        this.sistema = sistema;
        initComponents();
        setLocationRelativeTo(null); //Centra la ventana en la pantalla

        servidor = new ServidorCajero(sistema, this::agregarRegistro);

        // Cada segundo se refresca el estado y los hilos (este temporizador se ejecuta en el hilo de eventos de Swing)
        temporizador = new javax.swing.Timer(1000, e -> actualizarEstado());
        temporizador.start();

        // Al cerrar la ventana se detiene el servidor para liberar el puerto
        addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosing(java.awt.event.WindowEvent e) {
                servidor.detener();
            }
        });

        iniciarServidor();
    }

