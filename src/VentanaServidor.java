    /**
     * Inicia el servidor. Si no se puede (por ejemplo, el puerto ya está en uso porque hay otro servidor abierto) muestra el error.
     */
    private void iniciarServidor() {
        try {
            servidor.iniciar();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo iniciar el servidor en el puerto " + Protocolo.PUERTO + ": " + e.getMessage()
                    + "\nVerifique que no haya otro servidor abierto.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
        actualizarEstado();
    }

    /**
     * Agrega una línea al registro. Los mensajes los escriben los hilos del servidor, pero los componentes de Swing solo se pueden modificar
     * desde el hilo de eventos, por eso se usa invokeLater.
     */
    private void agregarRegistro(String mensaje) {
        SwingUtilities.invokeLater(() -> {
            txtRegistro.append(mensaje + "\n");
            txtRegistro.setCaretPosition(txtRegistro.getDocument().getLength()); //Baja al último mensaje
        });
    }

    /**
     * Actualiza el texto del estado, la cantidad de hilos y de cuentas, y habilita solo el botón que tiene sentido según si el servidor está iniciado o detenido.
     */
    private void actualizarEstado() {
        boolean activo = servidor.estaEjecutando();
        lblEstado.setText(activo ? "Estado: servidor en ejecución (puerto " + Protocolo.PUERTO + ")" : "Estado: servidor detenido");
        lblHilos.setText("Hilos en ejecución: " + servidor.getHilosActivos() + "   Hilos generados: " + servidor.getHilosGenerados());
        lblCuentas.setText("Cuentas registradas: " + sistema.cantidadCuentas());
        btnIniciar.setEnabled(!activo);
        btnDetener.setEnabled(activo);
    }

