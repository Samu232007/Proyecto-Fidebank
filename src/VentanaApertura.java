    /**
     * Botón Crear cuenta: valida los datos y los envía al servidor para que cree la cuenta. Si hay campos vacíos, la cédula o el teléfono no son números,
     * el PIN no tiene 4 dígitos o la confirmación no coincide se muestra "Revise los datos ingresados" y la ventana se mantiene para corregirlos.
     * La petición se hace en un hilo aparte (SwingWorker) para que la ventana no se congele mientras se espera la respuesta del servidor.
     */
    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
        String cedula = txtCedula.getText().trim();
        String nombre = txtNombre.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String pin = new String(txtPin.getPassword());
        String confirmar = new String(txtConfirmarPin.getPassword());

        // El cajero valida primero para no molestar al servidor con datos incorrectos, aunque el servidor también los valida
        if (!Formato.esNumero(cedula) || nombre.isEmpty() || apellidos.isEmpty() || !Formato.esNumero(telefono)
                || !pin.matches("\\d{4}") || !pin.equals(confirmar)) {
            JOptionPane.showMessageDialog(this, "Revise los datos ingresados", "Apertura de cuenta", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Cliente cliente = new Cliente(cedula, nombre, apellidos, telefono);

        // Mientras se espera la respuesta del servidor se deshabilitan los controles para evitar peticiones repetidas
        habilitarControles(false);

        new SwingWorker<String, Void>() {
            // Se ejecuta en un hilo aparte: envía la petición al servidor y devuelve el número de cuenta que se le asignó
            @Override
            protected String doInBackground() throws Exception {
                return ClienteRed.abrirCuenta(cliente, pin);
            }

            // Se ejecuta en el hilo de eventos cuando el servidor ya respondió
            @Override
            protected void done() {
                habilitarControles(true);
                try {
                    String numeroCuenta = get();
                    JOptionPane.showMessageDialog(VentanaApertura.this,
                            "Cuenta creada con éxito\nNúmero de cuenta: " + numeroCuenta + "\nUse este número para ingresar al cajero.",
                            "Apertura de cuenta",
                            JOptionPane.INFORMATION_MESSAGE);
                    dispose();
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                } catch (ExecutionException e) {
                    Mensajes.mostrarError(VentanaApertura.this, e, "Apertura de cuenta");
                }
            }
        }.execute();
    }//GEN-LAST:event_btnCrearActionPerformed

