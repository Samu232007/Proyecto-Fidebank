    /**
     * Botón Depositar: valida el monto y envía la petición de depósito al servidor.
     * La petición se hace en un hilo aparte (SwingWorker) para que la ventana no se congele mientras se espera la respuesta del servidor.
     */
    private void btnDepositarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDepositarActionPerformed
        // Si el monto está vacío o no es mayor a cero se muestra "Monto no válido" y el cliente lo puede corregir
        Double montoLeido = Mensajes.leerMonto(this, txtMonto.getText(), "Depósito");
        if (montoLeido == null) {
            return;
        }
        double monto = montoLeido;

        // Mientras se espera la respuesta del servidor se deshabilitan los controles para evitar peticiones repetidas
        habilitarControles(false);

        new SwingWorker<ResultadoOperacion, Void>() {
            // Se ejecuta en un hilo aparte: envía la petición al servidor, si no se puede realizar lanza ExcepcionInterna
            @Override
            protected ResultadoOperacion doInBackground() throws Exception {
                return ClienteRed.depositar(sesion, monto);
            }

            // Se ejecuta en el hilo de eventos cuando el servidor ya respondió
            @Override
            protected void done() {
                habilitarControles(true);
                try {
                    ResultadoOperacion resultado = get();
                    // Se muestra el aviso de transacción exitosa y al regresar de él se cierra esta ventana para volver al menú principal
                    new VentanaTransaccionExitosa(VentanaDeposito.this, true, sesion, resultado,
                            "Depósito realizado con éxito", null).setVisible(true);
                    dispose();
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                } catch (ExecutionException e) {
                    Mensajes.mostrarError(VentanaDeposito.this, e, "Depósito");
                }
            }
        }.execute();
    }//GEN-LAST:event_btnDepositarActionPerformed

