    /**
     * Crea el menú principal para el cliente que ingresó y muestra su saludo.
     */
    public VentanaMenu(VentanaInicio inicio, SesionCliente sesion) {
        this.inicio = inicio;
        this.sesion = sesion;
        initComponents();
        setLocationRelativeTo(null); //Centra la ventana en la pantalla

        lblSaludo.setText("Bienvenido, " + sesion.getNombreCompleto());
        lblCuenta.setText("Cuenta: " + sesion.getNumeroCuenta());

        // Cuando esta ventana se cierra (con Salir o con la X) se vuelve a mostrar la pantalla de inicio
        addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e) {
                VentanaMenu.this.inicio.setVisible(true);
            }
        });
    }

