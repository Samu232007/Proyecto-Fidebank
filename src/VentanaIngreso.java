    /**
     * Botón Ingresar: valida el formato de los datos y envía la petición de ingreso al servidor. Si el servidor da acceso se abre el menú principal,
     * si no (se lanza la ExcepcionInterna) se muestra "Número de cuenta o PIN incorrecto" y se permite intentarlo de nuevo.
     * La petición se hace en un hilo aparte (SwingWorker) para que la ventana no se congele mientras se espera la respuesta del servidor.
     */
    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String numeroCuenta = txtCuenta.getText().trim();
        String pin = new String(txtPin.getPassword());

        // Si el formato no es válido se muestra el mismo mensaje que cuando los datos no coinciden, así no se dan pistas
        if (!Formato.esNumero(numeroCuenta) || !pin.matches("\\d{4}")) {
            JOptionPane.showMessageDialog(this, "Número de cuenta o PIN incorrecto", "Ingreso", JOptionPane.WARNING_MESSAGE);
            txtPin.setText("");
            return;
        }

        // Mientras se espera la respuesta del servidor se deshabilitan los controles para evitar peticiones repetidas
        habilitarControles(false);

        new SwingWorker<SesionCliente, Void>() {
            // Se ejecuta en un hilo aparte: envía la petición al servidor, si los datos no son correctos lanza ExcepcionInterna
            @Override
            protected SesionCliente doInBackground() throws Exception {
                return ClienteRed.iniciarSesion(numeroCuenta, pin);
            }

            // Se ejecuta en el hilo de eventos cuando el servidor ya respondió
            @Override
            protected void done() {
                habilitarControles(true);
                try {
                    // Si el servidor dio acceso, se cierra esta ventana, se oculta el inicio y se abre el menú principal
                    SesionCliente sesion = get();
                    dispose();
                    inicio.setVisible(false);
                    new VentanaMenu(inicio, sesion).setVisible(true);
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                } catch (ExecutionException e) {
                    Mensajes.mostrarError(VentanaIngreso.this, e, "Ingreso");
                    txtPin.setText("");
                }
            }
        }.execute();
    }//GEN-LAST:event_btnIngresarActionPerformed

